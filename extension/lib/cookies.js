/**
 * Read YouTube cookies from this browser and format them as a Netscape
 * `cookies.txt`, which is the only form yt-dlp accepts.
 *
 * These cookies are account credentials: whoever holds them can sign in as you.
 * So they are only ever sent to a server the user has explicitly trusted, over
 * the connection they configured — never to a third party. The server keeps them
 * in memory for its own lifetime only (see server.py's CookieStore).
 */

// Chrome exposes httpOnly cookies to an extension, and those are exactly the
// ones yt-dlp needs to look signed in (SID, HSID, __Secure-*). Without the
// "cookies" permission they are invisible.
const YOUTUBE_URL = "https://www.youtube.com";

/**
 * A cookie is only worth sending if it can authenticate the session. Sending the
 * whole jar (consent, tracking, experiment flags) would be more data than needed
 * and would leak more than it has to.
 */
export function isAuthCookie(cookie) {
  const name = String(cookie?.name || "");
  if (!name) return false;
  return (
    name === "SID" ||
    name === "HSID" ||
    name === "SSID" ||
    name === "APISID" ||
    name === "SAPISID" ||
    name.startsWith("SIDCC") ||
    name.startsWith("SSIDCC") ||
    name.startsWith("__Secure-") ||
    name.startsWith("LOGIN_INFO")
  );
}

/**
 * Whether the cookie applies to subdomains. Chrome reports this as `hostOnly`
 * (a host-only cookie must not gain a leading dot), with the domain's leading dot
 * as a fallback.
 */
function isWildcard(cookie) {
  if (typeof cookie?.hostOnly === "boolean") return !cookie.hostOnly;
  return String(cookie?.domain || "").startsWith(".");
}

/**
 * Netscape wants a leading dot on a wildcard domain and none on a host-only one,
 * and the "include subdomains" column has to agree with it.
 */
function netscapeDomain(cookie) {
  const value = String(cookie?.domain || "").trim();
  if (!value) return ".youtube.com";
  if (value.startsWith(".")) return value;
  return isWildcard(cookie) ? `.${value}` : value;
}

/**
 * Turn a `chrome.cookies.Cookie[]` into Netscape `cookies.txt` text.
 * Pure, so it can be unit-tested without a browser.
 */
export function toNetscape(cookies) {
  const lines = ["# Netscape HTTP Cookie File", "# Generated by TunePull. Do not share."];
  for (const cookie of cookies || []) {
    if (!cookie?.name) continue;
    const domain = netscapeDomain(cookie);
    const subdomains = domain.startsWith(".") ? "TRUE" : "FALSE";
    const secure = cookie.secure ? "TRUE" : "FALSE";
    // Netscape uses a Unix timestamp; session cookies (-1) are written as 0.
    const expires = Number.isFinite(cookie.expirationDate)
      ? String(Math.floor(cookie.expirationDate))
      : "0";
    // HttpOnly cookies are marked with a "#HttpOnly_" prefix on the domain field,
    // which yt-dlp understands. Tab-separated, exactly 7 fields.
    const host = cookie.httpOnly ? `#HttpOnly_${domain}` : domain;
    lines.push(
      [host, subdomains, cookie.path || "/", secure, expires, cookie.name, cookie.value ?? ""].join(
        "\t",
      ),
    );
  }
  return lines.join("\n") + "\n";
}

/** Read the YouTube auth cookies visible to this extension. */
export async function gatherYoutubeCookies() {
  const cookies = await chrome.cookies.getAll({ url: YOUTUBE_URL });
  return (cookies || []).filter(isAuthCookie);
}

/** Read + format in one step. Returns { text, count }. */
export async function collectCookieFile() {
  const cookies = await gatherYoutubeCookies();
  return { text: toNetscape(cookies), count: cookies.length };
}
